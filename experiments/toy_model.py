#!/usr/bin/env python3
"""Numerical illustration for AI-generated academic satire; not empirical data."""

from __future__ import annotations

import argparse
import csv
import io
import math
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_N = (1, 4, 8, 16)
DEFAULT_PENALTY = 0.5


def solve_probability(single_draw: float, budget: int) -> float:
    """Probability of at least one success in independent draws with replacement."""
    if not math.isfinite(single_draw) or not 0 <= single_draw <= 1:
        raise ValueError("single_draw must be a finite probability")
    if isinstance(budget, bool) or not isinstance(budget, int) or budget < 0:
        raise ValueError("budget must be a nonnegative integer")
    if budget == 0 or single_draw == 0:
        return 0.0
    if single_draw == 1:
        return 1.0
    return -math.expm1(budget * math.log1p(-single_draw))


@dataclass(frozen=True)
class Result:
    n: int
    penalty: float
    budget: int
    mean_m: float
    mean_h: float
    log_mean_h: float
    ratio: float
    success_m: float
    success_h: float


def evaluate(n: int, penalty: float, *, valid_is_ugly: bool = True) -> Result:
    """Evaluate the constructed family; the reverse case makes valid candidates pretty.

    Means/ratios can overflow to infinity and probabilities can underflow to zero.
    log_mean_h retains the logarithmic mean for large finite penalty*n.
    """
    if isinstance(n, bool) or not isinstance(n, int) or n < 1:
        raise ValueError("n must be a positive integer")
    if not math.isfinite(penalty) or penalty < 0:
        raise ValueError("penalty must be finite and nonnegative")
    exponent = math.log(n) + (1 if valid_is_ugly else -1) * penalty * n
    # Stable log(1 + exp(exponent)), avoiding overflow in intermediate weights.
    log_mean_h = max(0.0, exponent) + math.log1p(math.exp(-abs(exponent)))
    try:
        mean_h = math.exp(log_mean_h)
    except OverflowError:
        mean_h = math.inf
    mean_m = n + 1
    single_h = math.exp(-log_mean_h)
    return Result(
        n=n,
        penalty=penalty,
        budget=n + 1,
        mean_m=mean_m,
        mean_h=mean_h,
        log_mean_h=log_mean_h,
        ratio=mean_h / mean_m,
        success_m=solve_probability(1 / mean_m, n + 1),
        success_h=solve_probability(single_h, n + 1),
    )


def csv_text(results: list[Result]) -> str:
    stream = io.StringIO(newline="")
    writer = csv.writer(stream, lineterminator="\n")
    writer.writerow(("n", "penalty", "budget", "mean_m", "mean_h", "ratio", "success_m", "success_h"))
    for r in results:
        writer.writerow((r.n, f"{r.penalty:g}", r.budget,
                         *(f"{v:.9g}" for v in (r.mean_m, r.mean_h, r.ratio, r.success_m, r.success_h))))
    return stream.getvalue()


def latex_text(results: list[Result]) -> str:
    lines = [
        "% AI-generated academic satire. Generated by experiments/toy_model.py --write.",
        "% Deterministic formula evaluations, not empirical measurements.",
        r"\begin{tabular}{rrrrrr}",
        r"\toprule",
        r"$n$ & $\E T_M$ & $\E T_H$ & Ratio & $\Prb(T_M\leq B)$ & $\Prb(T_H\leq B)$ \\",
        r"\midrule",
    ]
    for r in results:
        lines.append(f"{r.n} & {r.mean_m:,.0f} & {r.mean_h:,.2f} & {r.ratio:,.2f} & "
                     f"{r.success_m:.6f} & {r.success_h:.6f}" + r" \\")
    lines.extend((r"\bottomrule", r"\end{tabular}", ""))
    return "\n".join(lines)


def generated_files() -> dict[Path, str]:
    results = [evaluate(n, DEFAULT_PENALTY) for n in DEFAULT_N]
    return {
        ROOT / "experiments/results.csv": csv_text(results),
        ROOT / "paper/generated/toy-table.tex": latex_text(results),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--n", type=int, nargs="+", default=DEFAULT_N)
    parser.add_argument("--penalty", type=float, default=DEFAULT_PENALTY)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="regenerate the canonical tracked example")
    mode.add_argument("--check", action="store_true", help="check the canonical generated files are current")
    args = parser.parse_args()
    if (args.write or args.check) and (tuple(args.n) != DEFAULT_N or args.penalty != DEFAULT_PENALTY):
        parser.error("--write and --check use the canonical n values and penalty; omit custom parameters")
    try:
        results = [evaluate(n, args.penalty) for n in args.n]
    except ValueError as exc:
        parser.error(str(exc))
    if args.write or args.check:
        stale = []
        for path, expected in generated_files().items():
            if args.write:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(expected, encoding="utf-8")
                print(f"Wrote {path.relative_to(ROOT)}")
            elif not path.exists() or path.read_text(encoding="utf-8") != expected:
                stale.append(str(path.relative_to(ROOT)))
        if stale:
            parser.exit(1, "Stale generated files: " + ", ".join(stale) + "; run make tables\n")
        if args.check:
            print("Canonical CSV and LaTeX table are current.")
    else:
        print("# AI-generated academic satire; deterministic toy-model formulas, not empirical data.")
        print(csv_text(results), end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
